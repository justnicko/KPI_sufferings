# Словник - набір об'єктів з доступом по ключу
# Можливі ключі: рядок, число, кортеж
# Елементи розташовуються в довільному порядку
# (З пайтон 3.7 послідовність зберігається,
# як його генерували)
# Словники - відображення, а не послідовності
# Змінюваний тип даних

# Створення словників
# dict(<key1>=<value2><key1>=<value2>)
# dict(<dict1>)
# dict(<tuples with two elements (key, value)>)
# dict(<arrays with two elements [key, value]>)

dict1 = dict(a = 1, b = 3)
dict2 = dict((('a', 1), ('b', 2)))
print(dict1, dict2)

k = ['a', 'b', 'c']
v = [1, 2, 3]
a = list(zip(k, v))
print(dict(a))

# Створення з кортежами як ключем
d = {("Mn","Tu") : 1, ("Fr", "Wn") : 2}
print(d['Mn', 'Tu'])

# Заповнення поелементно
d = {}
d['a'] = 1
d['b'] = 2
print(d)

# Створення за допомогою dict.fromkeys()
# dict.fromkeys(<Послідовність>[, <Значення>])
keys = ['af','asdfas','zcvz','sadf']
print(dict.fromkeys(keys))
print(dict.fromkeys(keys), 0)

print('''
При створенні слованика в змінній
зберігається посилання, а не об'єкт
''')
d1 = d2 = {"a" : 1, 'b' : 2}
d2['b'] = 10
print(d1, d2)
print('='*50 + '\n')

print('Поверхневе копіювання словників')
d3 = {"a" : 1, 'b' : [234, 23, 213]}
d4 = d3.copy()
print(d3 is d4)
d3['b'][2] = 100
print(d3, d4)
print('='*50 + '\n')


print('Багаторівневі словники')
dd1 = {'a': 1, 'b': 2}
dd1['dd2'] = {'c': 3, 'd': 4}
dd1['dd2']['dd3'] = {'e': 5, 'f': 6}
print(dd1)
print('='*50 + '\n')

print("Перевірка існування ключа")
d5 = {"a": 145}
print("a" in d5, "b" in d5)
print('='*50 + '\n')

print("Метод get")
# get(<Ключ>[, <default>])
# За відсутності ключа,
# повернеться default (None за замовч.).
# Інакше, повернеться значення за ключем
d6 = {'copy': 111, 'get' : 112, 'bet': 113}
print((d6.get('copy'), d6.get('set')))
print('='*50 + '\n')

print("setdefault")
# Створює новий елемент зі значенням
# другого параметра (за замовч. None)
# Якщо ключ присутній у словнику, то
# метод поверне значення за ключем
print('='*50 + '\n')


print('Перебори')
# 1. keys() - повертає ітератор по ключам
d7 = {'copy': 111, 'get' : 112, 'bet': 113}
for i in d7.keys():
    print((i, d7[i]))

# 2. Просто перебирати по словнику
for i in d7:
    print((i, d7[i]))
print('='*50 + '\n')

print("values()")
d8 = {'asd': 1, 'aswe': 2}
print(list(d8.values()))
print('='*50 + '\n')

print("items()".ljust(50, '='))
d9 = {'asd': 1, 'aswe': 2}
print(list(d9.items()))
print('='*50 + '\n')

print("pop()")
# pop(<Ключ> [, <default>])
# Видаляє за ключем і повертає значення
# Якщо ключ відсутній, і є другий параметр,[]
# то повернеться значення другого параметра
# Якщо друг. парам. немає, прокид. помилка
d10 = {'asd': 1, 'aswe': 2}
print(d10.pop('asd'), d10.pop('aszz', None))
print('='*50 + '\n')

print('clear() '.ljust(50, '='))
d11 = {'a': 1, 'b': 23}
print(d11.clear())
print('='*50 + '\n')

